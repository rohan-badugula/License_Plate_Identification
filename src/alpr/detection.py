"""Ultralytics adapter: one foreground class, explicit original-image coordinates."""

import json
from pathlib import Path

import numpy as np

from .data import load_manifest
from .io import environment, new_run, sha256, write_json


def load_detector(weights: str | Path):
    from ultralytics import YOLO

    try:
        model = YOLO(str(weights))
    except ModuleNotFoundError as error:
        if error.name == "dill":
            raise ValueError(
                "Archived checkpoint requires dill; install paper-alpr[legacy]"
            ) from error
        raise
    if model.task != "detect" or len(model.names) != 1:
        raise ValueError("Expected a detector trained for one license-plate foreground class")
    return model


def validate_detector_data(data: Path, split: str) -> Path:
    """Make sure YOLO reads precisely the files audited in our prepared manifest."""
    root = data.parent.resolve()
    try:
        specification = json.loads(data.read_text())
    except json.JSONDecodeError as error:
        raise ValueError("Use data.yaml generated by alpr prepare-detection") from error
    if (
        Path(specification.get("path", "")).resolve() != root
        or specification.get("names") != {"0": "license_plate"}
        or any(specification.get(s) != f"images/{s}" for s in ("train", "val", "test"))
    ):
        raise ValueError("Detection YAML must reference its prepared single-class dataset")
    manifest = root / "manifest.csv"
    records = load_manifest(manifest, split)
    expected_images = {(root / r["path"]).resolve() for r in records}
    actual_images = {p.resolve() for p in (root / "images" / split).rglob("*") if p.is_file()}
    expected_labels = {(root / r["label_path"]).resolve() for r in records}
    actual_labels = {p.resolve() for p in (root / "labels" / split).rglob("*.txt")}
    if expected_images != actual_images or expected_labels != actual_labels:
        raise ValueError("Prepared directory contents do not match the manifest")
    return manifest


class PlateDetector:
    def __init__(
        self,
        weights: Path,
        *,
        confidence: float = 0.25,
        iou: float = 0.7,
        image_size: int = 640,
        device: str = "cpu",
    ):
        if not weights.is_file():
            raise FileNotFoundError(f"Plate detector checkpoint not found: {weights}")
        if not 0 <= confidence <= 1 or not 0 < iou <= 1 or image_size < 32:
            raise ValueError("Invalid detector confidence, IoU or image size")
        self.model = load_detector(weights)
        self.kwargs = {
            "conf": confidence,
            "iou": iou,
            "imgsz": image_size,
            "device": device,
            "verbose": False,
        }

    def predict(self, image: np.ndarray) -> list[dict]:
        result = self.model.predict(source=image, **self.kwargs)[0]
        if result.boxes is None:
            return []
        return [
            {"box": box, "confidence": confidence}
            for box, confidence in zip(
                result.boxes.xyxy.cpu().tolist(), result.boxes.conf.cpu().tolist(), strict=True
            )
        ]


def train_detector(
    data: Path,
    output: Path,
    *,
    model: str = "yolov8n.pt",
    epochs: int = 10,
    batch_size: int = 16,
    image_size: int = 640,
    device: str = "cpu",
    seed: int = 42,
    pretrained: bool = True,
) -> dict:
    from ultralytics import YOLO

    if epochs < 1 or batch_size < 1 or image_size < 32:
        raise ValueError("Invalid detector training dimensions, batch size or epochs")
    if not data.is_file():
        raise FileNotFoundError(data)
    # Prepared manifests are audited before fitting; arbitrary YOLO datasets need preparation first.
    manifest = validate_detector_data(data, "train")
    validate_detector_data(data, "val")
    if (
        Path(model).name
        not in {f"yolov8{size}.{suffix}" for size in "nsmlx" for suffix in ("pt", "yaml")}
        and not Path(model).is_file()
    ):
        raise ValueError("Use a YOLOv8 checkpoint or architecture, not a different YOLO generation")
    output = new_run(output).resolve()
    detector = YOLO(model)
    result = detector.train(
        data=str(data.resolve()),
        epochs=epochs,
        batch=batch_size,
        imgsz=image_size,
        device=device,
        seed=seed,
        deterministic=True,
        project=str(output),
        name="fit",
        exist_ok=False,
        workers=0,
        pretrained=pretrained,
        fliplr=0.0,
        flipud=0.0,
        plots=True,
    )
    summary = {
        "environment": environment(),
        "data_sha256": sha256(data),
        "manifest_sha256": sha256(manifest),
        "model": model,
        "epochs": epochs,
        "batch_size": batch_size,
        "image_size": image_size,
        "device": device,
        "seed": seed,
        "pretrained": pretrained,
        "horizontal_flip": 0.0,
        "best_checkpoint": str(detector.trainer.best),
        "validation": result.results_dict if result else {},
    }
    write_json(output / "experiment.json", summary)
    return summary


def evaluate_detector(
    data: Path,
    weights: Path,
    output: Path,
    *,
    split: str = "test",
    image_size: int = 640,
    device: str = "cpu",
) -> dict:
    validate_detector_data(data, split)
    detector = load_detector(weights)
    output = new_run(output).resolve()
    metrics = detector.val(
        data=str(data.resolve()),
        split=split,
        imgsz=image_size,
        device=device,
        project=str(output),
        name="evaluation",
        workers=0,
        plots=True,
    )
    summary = {
        "split": split,
        "mAP50": float(metrics.box.map50),
        "mAP50_95": float(metrics.box.map),
        "precision": float(metrics.box.mp),
        "recall": float(metrics.box.mr),
        "checkpoint_sha256": sha256(weights),
        "manifest_sha256": sha256(data.parent / "manifest.csv"),
        "environment": environment(),
        "device": device,
    }
    write_json(output / "metrics.json", summary)
    return summary
